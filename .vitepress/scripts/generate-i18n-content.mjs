import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { basename, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { contentTranslations, messages } from '../i18n-messages.mjs'

const rootDir = fileURLToPath(new URL('../..', import.meta.url))
const sourcePostDir = join(rootDir, 'post')
const generatedLocales = ['en', 'fr']
const generatedComment = 'This file is generated by `.vitepress/scripts/generate-i18n-content.mjs`. Edit `post/` sources or `.vitepress/i18n-messages.mjs` instead.'

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

const translateLine = (line, dictionary) => {
  return Object.entries(dictionary)
    .sort(([sourceA], [sourceB]) => sourceB.length - sourceA.length)
    .reduce((translatedLine, [source, target]) => {
      return translatedLine.replace(new RegExp(escapeRegExp(source), 'g'), target)
    }, line)
}

const translateMarkdown = (source, locale) => {
  const dictionary = contentTranslations[locale] ?? {}
  let fence = ''

  return source
    .split('\n')
    .map((line) => {
      const fenceMatch = line.match(/^\s*(`+|~+)/)

      if (fence) {
        if (fenceMatch) {
          const sameFenceChar = fenceMatch[1][0] === fence[0]
          const longEnoughFence = fenceMatch[1].length >= fence.length

          if (sameFenceChar && longEnoughFence) fence = ''
        }

        return line
      }

      if (fenceMatch && fenceMatch[1].length >= 3) {
        fence = fenceMatch[1]
        return line
      }

      return translateLine(line, dictionary)
    })
    .join('\n')
}

const postLink = (locale, slug) => `/${locale}/post/${slug}`

const renderHome = (locale) => {
  const message = messages[locale]

  return `---
# ${generatedComment}
# https://vitepress.dev/reference/default-theme-home-page
layout: home

hero:
  name: "${message.title}"
  text: "${message.home.heroText}"
  tagline: "${message.home.tagline}"
 
  image:
    light: /dark.jpeg
    dark: /light.jpeg
  actions:
    - theme: brand
      text: ${message.home.actions.markdownExamples}
      link: ${postLink(locale, 'markdown-examples')}
    - theme: brand
      text: ${message.home.actions.apiExamples}
      link: ${postLink(locale, 'api-examples')}
    - theme: brand
      text: ${message.home.actions.mathDemo}
      link: ${postLink(locale, 'math')}

features:
${message.home.features.map((feature) => `  - title: ${feature.title}\n    details: ${feature.details}`).join('\n')}
---
`
}

const withGeneratedComment = (markdown) => {
  const comment = `<!-- ${generatedComment} -->`

  if (!markdown.startsWith('---\n')) return `${comment}\n${markdown}`

  const frontmatterEnd = markdown.indexOf('\n---', 4)

  if (frontmatterEnd === -1) return `${comment}\n${markdown}`

  const closingFenceEnd = frontmatterEnd + '\n---'.length

  return `${markdown.slice(0, closingFenceEnd)}\n${comment}${markdown.slice(closingFenceEnd)}`
}

const sourcePosts = (await readdir(sourcePostDir))
  .filter((file) => file.endsWith('.md'))
  .sort()

for (const locale of generatedLocales) {
  const localeDir = join(rootDir, locale)
  const localePostDir = join(localeDir, 'post')

  await rm(localeDir, { recursive: true, force: true })
  await mkdir(localePostDir, { recursive: true })
  await writeFile(join(localeDir, 'index.md'), renderHome(locale))

  for (const post of sourcePosts) {
    const source = await readFile(join(sourcePostDir, post), 'utf8')
    const translated = translateMarkdown(source, locale)
    await writeFile(join(localePostDir, basename(post)), withGeneratedComment(translated))
  }
}
